CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('USER', 'ADMIN'))
);
CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(4000),
    start_date DATE,
    end_date DATE,
    status VARCHAR(24) NOT NULL CHECK (status IN ('INITIATED', 'IN_PROGRESS', 'COMPLETED')),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    CHECK (start_date IS NULL OR end_date IS NULL OR start_date <= end_date)
);
CREATE INDEX projects_owner_idx ON projects(owner_id);
CREATE TABLE project_members (
    project_id BIGINT NOT NULL REFERENCES projects(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY (project_id, user_id)
);
CREATE INDEX project_members_user_idx ON project_members(user_id);
CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(4000),
    priority VARCHAR(16) NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    status VARCHAR(24) NOT NULL CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED')),
    due_date DATE,
    project_id BIGINT NOT NULL REFERENCES projects(id),
    assignee_id BIGINT REFERENCES users(id)
);
CREATE INDEX tasks_project_idx ON tasks(project_id, id);
CREATE INDEX tasks_assignee_idx ON tasks(assignee_id);
CREATE INDEX tasks_due_idx ON tasks(due_date, id);
CREATE TABLE labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(100) NOT NULL UNIQUE,
    color VARCHAR(7) NOT NULL
);
CREATE TABLE task_labels (
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    label_id BIGINT NOT NULL REFERENCES labels(id),
    PRIMARY KEY (task_id, label_id)
);
CREATE INDEX task_labels_label_idx ON task_labels(label_id);
CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    text VARCHAR(4000) NOT NULL,
    timestamp TIMESTAMP NOT NULL
);
CREATE INDEX comments_task_idx ON comments(task_id, id);
CREATE TABLE attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    dropbox_file_id VARCHAR(255) NOT NULL UNIQUE,
    filename VARCHAR(255) NOT NULL,
    upload_date TIMESTAMP NOT NULL
);
CREATE INDEX attachments_task_idx ON attachments(task_id, id);
